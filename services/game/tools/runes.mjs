// Laptop only: node tools/runes.mjs [sheet.svg] -> web/runes.js
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('.', import.meta.url);
const src = readFileSync(process.argv[2] || new URL('runic-letters.svg', dir), 'utf8');
const W = 44, H = 64; // glyph box; the sheet's rune card centre lands on the box centre
const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const rnd = n => +n.toFixed(1);
const out = {};
for (const m of src.matchAll(/<path d="([^"]+)" stroke-width="4"[^>]*\/>/g)) {
  const toks = m[1].match(/[MLHV]|-?[\d.]+/g);
  const x0 = +toks[1], y0 = +toks[2];
  const col = Math.floor((x0 - 87.5) / 249), row = y0 < 700 ? 0 : 1;
  const cx = 87.5 + 249 * col + 104, cy = (row ? 609.5 : 127.5) + 213 + 106;
  const ch = letters[row * 13 + col];
  let d = '', cmd, cur = [0, 0];
  const p = (x, y) => `${rnd(x - cx + W / 2)} ${rnd(y - cy + H / 2)}`;
  for (let i = 0; i < toks.length;) {
    if (/[MLHV]/.test(toks[i])) cmd = toks[i++];
    if (cmd === 'H') cur[0] = +toks[i++]; else if (cmd === 'V') cur[1] = +toks[i++];
    else { cur = [+toks[i], +toks[i + 1]]; i += 2; }
    d += (cmd === 'M' ? 'M' : 'L') + p(...cur);
  }
  (out[ch] ??= []).push(d);
}
// The sheet has no Y rune: a Y-shaped one in the same style.
out.Y = ['M12 2L22 20L32 2', 'M22 20V62'];
const missing = [...letters].filter(c => !out[c]);
if (missing.length) throw new Error('no rune for ' + missing);
const data = [...letters].map(c => `${c}:"${out[c].join(' ')}"`).join(',\n');
writeFileSync(new URL('../web/runes.js', import.meta.url), `// Generated by tools/runes.mjs from tools/runic-letters.svg. Do not edit.
const RUNES = {
${data}
};
function runeSvg(ch) {
  const open = w => '<svg class="rune" viewBox="0 0 ' + w + ' ${H}" fill="none" stroke="currentColor" stroke-width="4" stroke-linejoin="bevel" aria-hidden="true">';
  const c = String(ch).toUpperCase();
  if (c === ' ') return open(22) + '</svg>';
  const d = Object.hasOwn(RUNES, c) ? RUNES[c] : null;
  if (!d) return String(ch).replace(/[&<>"]/g, s => '&#' + s.charCodeAt(0) + ';');
  return open(${W}) + d.split(' M').map((s, i) => '<path d="' + (i ? 'M' : '') + s + '"/>').join('') + '</svg>';
}
`);
